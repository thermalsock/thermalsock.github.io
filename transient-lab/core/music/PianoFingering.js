function rootFromPackName(name) {
  return name.split(" ")[0];
}

export function getFingering(pack) {
  const table = pack.scaleType === "major" || pack.scaleType === "ionian" ? MAJOR_FINGERING : pack.scaleType === "minor" || pack.scaleType === "aeolian" ? NATURAL_MINOR_FINGERING : null;
  if (!table) return null;
  const root = rootFromPackName(pack.name);
  return table[root] || null;
}